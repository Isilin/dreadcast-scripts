#!/usr/bin/env node
// Keeps the offline fallback list embedded in the Script Manager in sync with
// data/scripts.json, which is the single source of truth.
//
//   node tools/sync-fallback.mjs           rewrite the generated block
//   node tools/sync-fallback.mjs --check   exit 1 if the block has drifted (CI)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'data', 'scripts.json');
const TARGET = join(ROOT, 'src', 'scripts', 'script-manager.js');

// Markers are kept ASCII-only so they always match, whatever the encoding.
const START =
  '// === DCSM_FALLBACK_START - generated by tools/sync-fallback.mjs, do not edit by hand ===';
const END = '// === DCSM_FALLBACK_END ===';

const fail = (message) => {
  console.error(`sync-fallback: ${message}`);
  process.exit(1);
};

// The list is injected inside a template literal, so only backslashes,
// backticks and interpolation openings need to be neutralized.
const escapeForTemplate = (text) =>
  text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const buildBlock = (list) =>
  [
    START,
    'const DCSM_FALLBACK_LIST = JSON.parse(`',
    escapeForTemplate(JSON.stringify(list, null, 2)),
    '`);',
    END,
  ].join('\n');

const readList = () => {
  let list;
  try {
    list = JSON.parse(readFileSync(SOURCE, 'utf8'));
  } catch (error) {
    fail(`data/scripts.json is unreadable or invalid: ${error.message}`);
  }

  if (!Array.isArray(list) || list.length === 0) {
    fail('data/scripts.json should be a non empty array.');
  }

  list.forEach((script, index) => {
    if (typeof script?.id !== 'string' || script.id === '') {
      fail(`entry #${index}: 'id' is missing or empty.`);
    }
    if (typeof script.url !== 'string' || script.url === '') {
      fail(`entry #${index} ('${script.id}'): 'url' is missing or empty.`);
    }
  });

  return list;
};

const locateBlock = (file) => {
  const start = file.indexOf(START);
  const end = file.indexOf(END);

  if (start === -1) {
    fail(`start marker not found in ${TARGET}.`);
  }
  if (end === -1) {
    fail(`end marker not found in ${TARGET}.`);
  }
  if (file.indexOf(START, start + 1) !== -1) {
    fail('start marker found more than once.');
  }
  if (file.indexOf(END, end + 1) !== -1) {
    fail('end marker found more than once.');
  }
  if (end < start) {
    fail('end marker comes before the start marker.');
  }

  return { start, end: end + END.length };
};

const check = process.argv.includes('--check');
const file = readFileSync(TARGET, 'utf8');
const { start, end } = locateBlock(file);
const list = readList();
const block = buildBlock(list);

if (file.slice(start, end) === block) {
  console.log(`sync-fallback: fallback list is up to date (${list.length}).`);
  process.exit(0);
}

if (check) {
  fail("the embedded fallback list has drifted from data/scripts.json. Run 'yarn sync:fallback'.");
}

writeFileSync(TARGET, file.slice(0, start) + block + file.slice(end), 'utf8');
console.log(`sync-fallback: fallback list regenerated (${list.length}).`);
